// Clean specific items by moving them to the Trash (non-destructive)
ipcMain.handle('clean-targets', async (event, pathsToClean) => {
  let successCount = 0;
  let failCount = 0;
  let freedSize = 0;

  for (const itemPath of pathsToClean) {
    if (isBlocked(itemPath)) {
      failCount++;
      continue;
    }

    try {
      if (fs.existsSync(itemPath)) {
        let itemSize = 0;
        const stats = await fsPromises.lstat(itemPath);
        if (stats.isDirectory()) {
          itemSize = await getDirectorySize(itemPath);
        } else {
          itemSize = stats.size;
        }

        // Electron native trash shell call (Safe, reversible deletion)
        await shell.trashItem(itemPath);
        successCount++;
        freedSize += itemSize;
      } else {
        failCount++;
      }
    } catch (e) {
      failCount++;
    }
  }

  return {
    success: true,
    successCount,
    failCount,
    freedSize: formatBytes(freedSize)
  };
});

