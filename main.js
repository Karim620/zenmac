function execFilePromise(cmd, args) {
  return new Promise((resolve) => {
    require('child_process').execFile(cmd, args, { maxBuffer: 10 * 1024 * 1024 }, (err, stdout) => {
      if (err) resolve(null);
      else resolve(stdout ? stdout.trim() : null);
    });
  });
}

async function getAppInfoPlist(appPath) {
  const plistPath = path.join(appPath, 'Contents', 'Info.plist');
  if (!fs.existsSync(plistPath)) return null;
  const jsonStr = await execFilePromise('plutil', ['-convert', 'json', '-o', '-', plistPath]);
  if (!jsonStr) return null;
  try {
    return JSON.parse(jsonStr);
  } catch (e) {
    return null;
  }
}

async function getAppArchitecture(appPath, infoPlist) {
  if (!infoPlist || !infoPlist.CFBundleExecutable) return 'Universal';
  const execPath = path.join(appPath, 'Contents', 'MacOS', infoPlist.CFBundleExecutable);
  if (!fs.existsSync(execPath)) return 'Universal';
  
  const fileOut = await execFilePromise('file', [execPath]);
  if (!fileOut) return 'Universal';
  
  const lower = fileOut.toLowerCase();
  if (lower.includes('universal binary') || (lower.includes('x86_64') && lower.includes('arm64'))) {
    return 'Universal';
  } else if (lower.includes('arm64')) {
    return 'Apple Silicon';
  } else if (lower.includes('x86_64') || lower.includes('i386')) {
    return 'Intel';
  }
  return 'Universal';
}

async function getAppSize(appPath) {
  try {
    const duOut = await execFilePromise('du', ['-sk', appPath]);
    if (duOut) {
      const parts = duOut.split(/\s+/);
      const kb = parseInt(parts[0], 10);
      if (!isNaN(kb)) return kb * 1024;
    }
  } catch (e) {}
  return await getDirectorySize(appPath);
}

