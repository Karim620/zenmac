async function getDirectoryStatsHelper(dirPath) {
  let totalSize = 0;
  let fileCount = 0;
  let maxMtime = 0;

  async function walk(currentPath) {
    try {
      const files = await fsPromises.readdir(currentPath, { withFileTypes: true });
      for (const f of files) {
        const full = path.join(currentPath, f.name);
        try {
          const stat = await fsPromises.lstat(full);
          if (stat.mtimeMs > maxMtime) maxMtime = stat.mtimeMs;
          if (stat.isDirectory()) {
            await walk(full);
          } else {
            totalSize += stat.size;
            fileCount++;
          }
        } catch (e) {}
      }
    } catch (e) {}
  }

  try {
    const stat = await fsPromises.lstat(dirPath);
    if (!stat.isDirectory()) {
      return { size: stat.size, fileCount: 1, mtime: stat.mtimeMs };
    }
    await walk(dirPath);
  } catch (e) {}

  return { size: totalSize, fileCount, mtime: maxMtime };
}

async function getAppCaches(appName, bundleId) {
  const cacheLocations = [];
  const searchTerms = [bundleId, appName, appName.replace(/\s+/g, '')].filter(t => t && t.length > 2);

  const candidateDirs = [
    { type: 'Caches', base: path.join(HOME, 'Library/Caches') },
    { type: 'Application Support', base: path.join(HOME, 'Library/Application Support') },
    { type: 'Logs', base: path.join(HOME, 'Library/Logs') },
    { type: 'Containers', base: path.join(HOME, 'Library/Containers') },
    { type: 'Group Containers', base: path.join(HOME, 'Library/Group Containers') },
    { type: 'WebKit', base: path.join(HOME, 'Library/WebKit') },
    { type: 'Saved State', base: path.join(HOME, 'Library/Saved Application State') },
    { type: 'HTTPStorages', base: path.join(HOME, 'Library/HTTPStorages') },
    { type: 'Cookies', base: path.join(HOME, 'Library/Cookies') },
  ];

  for (const loc of candidateDirs) {
    if (!fs.existsSync(loc.base)) continue;
    try {
      const items = await fsPromises.readdir(loc.base);
      for (const item of items) {
        const itemLower = item.toLowerCase();
        const matches = searchTerms.some(term => itemLower.includes(term.toLowerCase()));
        if (matches) {
          const fullPath = path.join(loc.base, item);
          
          if (loc.type === 'Caches' || loc.type === 'Containers') {
            try {
              const stat = await fsPromises.lstat(fullPath);
              if (stat.isDirectory()) {
                const subItems = await fsPromises.readdir(fullPath);
                let addedSub = false;
                for (const sub of subItems) {
                  const subLower = sub.toLowerCase();
                  if (['cache', 'gpu-cache', 'gpucache', 'code cache', 'service worker', 'logs', 'webkit', 'httpstorages', 'blob_storage', 'cacheddata'].some(k => subLower.includes(k))) {
                    const subPath = path.join(fullPath, sub);
                    const stats = await getDirectoryStatsHelper(subPath);
                    if (stats.size > 0) {
                      addedSub = true;
                      cacheLocations.push({
                        category: loc.type,
                        name: sub,
                        path: subPath,
                        size: stats.size,
                        fileCount: stats.fileCount,
                        mtime: stats.mtime
                      });
                    }
                  }
                }
                if (!addedSub) {
                  const stats = await getDirectoryStatsHelper(fullPath);
                  if (stats.size > 0) {
                    cacheLocations.push({
                      category: loc.type,
                      name: item,
                      path: fullPath,
                      size: stats.size,
                      fileCount: stats.fileCount,
                      mtime: stats.mtime
                    });
                  }
                }
              }
            } catch (e) {}
          } else if (loc.type === 'Application Support') {
            try {
              const stat = await fsPromises.lstat(fullPath);
              if (stat.isDirectory()) {
                const subItems = await fsPromises.readdir(fullPath);
                for (const sub of subItems) {
                  const subLower = sub.toLowerCase();
                  if (['cache', 'caches', 'cacheddata', 'gpu-cache', 'gpucache', 'code cache', 'service worker', 'logs', 'crashpad', 'blob_storage', 'dawncache', 'shadercache'].some(k => subLower.includes(k))) {
                    const subPath = path.join(fullPath, sub);
                    const stats = await getDirectoryStatsHelper(subPath);
                    if (stats.size > 0) {
                      cacheLocations.push({
                        category: 'App Support Cache',
                        name: `${item}/${sub}`,
                        path: subPath,
                        size: stats.size,
                        fileCount: stats.fileCount,
                        mtime: stats.mtime
                      });
                    }
                  }
                }
              }
            } catch (e) {}
          } else {
            const stats = await getDirectoryStatsHelper(fullPath);
            if (stats.size > 0) {
              cacheLocations.push({
                category: loc.type,
                name: item,
                path: fullPath,
                size: stats.size,
                fileCount: stats.fileCount,
                mtime: stats.mtime
              });
            }
          }
        }
      }
    } catch (e) {}
  }

  return cacheLocations;
}

ipcMain.handle('scan-applications', async () => {
  const appDirs = [
    '/Applications',
    path.join(HOME, 'Applications'),
    '/System/Applications',
    '/System/Applications/Utilities'
  ];

  const foundAppPaths = new Set();

  for (const dir of appDirs) {
    if (!fs.existsSync(dir)) continue;
    try {
      const files = await fsPromises.readdir(dir);
      for (const file of files) {
        const fullPath = path.join(dir, file);
        if (file.endsWith('.app')) {
          foundAppPaths.add(fullPath);
        } else if (!file.startsWith('.')) {
          try {
            const stat = await fsPromises.stat(fullPath);
            if (stat.isDirectory()) {
              const subFiles = await fsPromises.readdir(fullPath);
              for (const subFile of subFiles) {
                if (subFile.endsWith('.app')) {
                  foundAppPaths.add(path.join(fullPath, subFile));
                }
              }
            }
          } catch (e) {}
        }
      }
    } catch (e) {}
  }

  const appPromises = Array.from(foundAppPaths).map(async (appPath) => {
    try {
      const stat = await fsPromises.stat(appPath);
      const info = await getAppInfoPlist(appPath);
      
      const name = (info && (info.CFBundleDisplayName || info.CFBundleName)) || path.basename(appPath, '.app');
      const bundleId = (info && info.CFBundleIdentifier) || 'unknown';
      const version = (info && (info.CFBundleShortVersionString || info.CFBundleVersion)) || '1.0';
      
      let developer = 'Apple';
      if (info) {
        if (info.CFBundleGetInfoString) developer = info.CFBundleGetInfoString;
        else if (info.NSHumanReadableCopyright) developer = info.NSHumanReadableCopyright;
        else if (bundleId.startsWith('com.apple.')) developer = 'Apple Inc.';
        else if (bundleId.startsWith('com.microsoft.')) developer = 'Microsoft Corporation';
        else if (bundleId.startsWith('com.google.')) developer = 'Google LLC';
        else if (bundleId.startsWith('org.mozilla.')) developer = 'Mozilla Foundation';
        else if (bundleId.includes('.')) {
          const parts = bundleId.split('.');
          developer = parts[1] ? parts[1].charAt(0).toUpperCase() + parts[1].slice(1) : 'Developer';
        } else {
          developer = 'Third-Party Developer';
        }
      }

      let iconDataUrl = '';
      try {
        const nativeIcon = await app.getFileIcon(appPath, { size: 'normal' });
        iconDataUrl = nativeIcon.toDataURL();
      } catch (e) {}

      const appSize = await getAppSize(appPath);
      const architecture = await getAppArchitecture(appPath, info);
      const category = categorizeApp(name, bundleId, appPath, info);
      const permissions = getAppPermissions(info);
      const caches = await getAppCaches(name, bundleId);
      const cacheSize = caches.reduce((acc, c) => acc + c.size, 0);

      const installDate = stat.birthtimeMs || stat.ctimeMs || stat.mtimeMs;
      const modDate = stat.mtimeMs;

      return {
        name,
        bundleId,
        version,
        developer,
        path: appPath,
        icon: iconDataUrl,
        appSize,
        cacheSize,
        category,
        architecture,
        permissions,
        caches,
        installDate,
        modDate
      };
    } catch (e) {
      return null;
    }
  });

  const apps = (await Promise.all(appPromises)).filter(Boolean);

  const totalAppsCount = apps.length;
  const totalAppsSize = apps.reduce((acc, a) => acc + a.appSize, 0);
  const totalCacheSize = apps.reduce((acc, a) => acc + a.cacheSize, 0);

  let largestApp = apps.length > 0 ? apps.reduce((prev, curr) => curr.appSize > prev.appSize ? curr : prev) : null;
  let largestCache = apps.length > 0 ? apps.reduce((prev, curr) => curr.cacheSize > prev.cacheSize ? curr : prev) : null;

  return {
    apps,
    summary: {
      totalAppsCount,
      totalAppsSize,
      totalCacheSize,
      largestAppName: largestApp ? largestApp.name : 'N/A',
      largestAppSize: largestApp ? largestApp.appSize : 0,
      largestAppIcon: largestApp ? largestApp.icon : '',
      largestCacheName: largestCache ? largestCache.name : 'N/A',
      largestCacheSize: largestCache ? largestCache.cacheSize : 0,
      largestCacheIcon: largestCache ? largestCache.icon : ''
    }
  };
});

ipcMain.handle('clean-app-cache', async (event, { appPath, cachePaths }) => {
  let freedBytes = 0;
  let successCount = 0;
  let failCount = 0;

  for (const cPath of cachePaths) {
    if (!cPath || cPath === appPath || cPath.endsWith('.app') || cPath.includes('.app/')) {
      failCount++;
      continue;
    }

    if (isBlocked(cPath)) {
      failCount++;
      continue;
    }

    try {
      if (fs.existsSync(cPath)) {
        const stats = await getDirectoryStatsHelper(cPath);
        await shell.trashItem(cPath);
        freedBytes += stats.size;
        successCount++;
      } else {
        failCount++;
      }
    } catch (e) {
      failCount++;
    }
  }

  return {
    success: true,
    freedSize: formatBytes(freedBytes),
    freedBytes,
    successCount,
    failCount
  };
});

ipcMain.handle('open-app-path', async (event, appPath) => {
  if (fs.existsSync(appPath)) {
    await shell.openPath(appPath);
    return true;
  }
  return false;
});

ipcMain.handle('reveal-in-finder', async (event, targetPath) => {
  if (fs.existsSync(targetPath)) {
    shell.showItemInFolder(targetPath);
    return true;
  }
  return false;
});