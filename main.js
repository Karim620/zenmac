// Helper to normalize paths for case-insensitive comparison on macOS
function normalizePath(p) {
  if (!p || typeof p !== 'string') return '';
  return path.resolve(p).toLowerCase();
}

// Pre-normalize blocked paths on startup for performance & case insensitivity
const NORMALIZED_BLOCKED_PREFIXES = BLOCKED_PREFIXES.map(normalizePath);
const NORMALIZED_BLOCKED_LITERALS = BLOCKED_LITERALS.map(normalizePath);

// Pre-resolve blocked realpaths on startup for symlink check
const RESOLVED_BLOCKED_PREFIXES = BLOCKED_PREFIXES.map(p => {
  try { return normalizePath(fs.realpathSync(p)); } catch (e) { return normalizePath(p); }
});
const RESOLVED_BLOCKED_LITERALS = BLOCKED_LITERALS.map(p => {
  try { return normalizePath(fs.realpathSync(p)); } catch (e) { return normalizePath(p); }
});

// Helper checking normalized target path against literal and prefix blocklists
function matchesBlocklists(normPath, literalList, prefixList) {
  if (!normPath) return true;

  if (literalList.includes(normPath)) {
    return true;
  }

  for (const prefixPath of prefixList) {
    if (normPath === prefixPath) {
      return true;
    }
    const prefixWithSep = prefixPath.endsWith(path.sep) ? prefixPath : prefixPath + path.sep;
    if (normPath.startsWith(prefixWithSep)) {
      return true;
    }
  }
  return false;
}

// 4. Safety Validation Helper (Fails CLOSED on unresolved/suspicious paths)
function isBlocked(targetPath) {
  if (!targetPath || typeof targetPath !== 'string') {
    return true; // Fail closed if path is invalid
  }

  // 1. Check normalized string path first (protects against traversal attempts, relative paths, case variations)
  const normalized = normalizePath(targetPath);
  if (matchesBlocklists(normalized, NORMALIZED_BLOCKED_LITERALS, NORMALIZED_BLOCKED_PREFIXES)) {
    return true;
  }

  // 2. Resolve realpath to mitigate symlinks pointing to sensitive directories
  try {
    const resolved = normalizePath(fs.realpathSync(targetPath));
    if (matchesBlocklists(resolved, RESOLVED_BLOCKED_LITERALS, RESOLVED_BLOCKED_PREFIXES)) {
      return true;
    }
  } catch (e) {
    // Fail closed: If realpathSync fails (broken symlink, missing target, permission error),
    // treat the path as blocked to prevent operating on unresolvable or dangerous paths.
    return true;
  }

  return false;
}

// 5. Recursive Directory Size Calculation
async function getDirectorySize(dirPath) {
  let totalSize = 0;
  
  if (isBlocked(dirPath)) {
    return 0;
  }

  try {
    const files = await fsPromises.readdir(dirPath, { withFileTypes: true });
    for (const file of files) {
      const filePath = path.join(dirPath, file.name);
      
      if (isBlocked(filePath)) {
        continue;
      }

      if (file.isDirectory()) {
        totalSize += await getDirectorySize(filePath);
      } else if (file.isFile() || file.isSymbolicLink()) {
        try {
          const stats = await fsPromises.lstat(filePath);
          totalSize += stats.size;
        } catch (e) {
          // File might have changed or deleted during run
        }
      }
    }
  } catch (e) {
    // Permission denied or unreadable folder
  }
  return totalSize;
}

// 6. Whitelist Target Scanning
async function scanTarget(target) {
  if (!fs.existsSync(target.path)) {
    return { id: target.id, name: target.name, description: target.description, size: 0, itemsCount: 0, exists: false, items: [] };
  }

  if (isBlocked(target.path)) {
    return { id: target.id, name: target.name, description: target.description, size: 0, itemsCount: 0, exists: false, items: [] };
  }

  let totalSize = 0;
  let items = [];

  try {
    if (target.type === 'directory_contents') {
      const children = await fsPromises.readdir(target.path);
      
      // Parallelize target scanning using Promise.all for high performance
      const scanPromises = children.map(async (child) => {
        const childPath = path.join(target.path, child);
        if (isBlocked(childPath)) return null;

        try {
          const stats = await fsPromises.lstat(childPath);
          let size = 0;
          if (stats.isDirectory()) {
            size = await getDirectorySize(childPath);
          } else {
            size = stats.size;
          }
          return { name: child, path: childPath, size };
        } catch (e) {
          return null;
        }
      });

      const results = await Promise.all(scanPromises);
      for (const result of results) {
        if (result) {
          totalSize += result.size;
          items.push(result);
        }
      }
    } else {
      // Walk the whole directory
      totalSize = await getDirectorySize(target.path);
      items.push({ name: path.basename(target.path), path: target.path, size: totalSize });
    }
  } catch (e) {
    // Ignore read errors
  }

  // Sort items by size descending
  items.sort((a, b) => b.size - a.size);

  return {
    id: target.id,
    name: target.name,
    description: target.description,
    size: totalSize,
    itemsCount: items.length,
    exists: true,
    items,
    path: target.path
  };
}

// Format bytes to readable size
function formatBytes(bytes, decimals = 2) {
  if (bytes === 0) return '0 Bytes';
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ['Bytes', 'KB', 'MB', 'GB', 'TB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(dm)) + ' ' + sizes[i];
}

